#' Average a (age, year, value) table over years at given ages
#' @param df Data frame with columns \code{age}, \code{year} and \code{col}.
#' @param col Name of the value column.
#' @param years,ages Years to average over and ages to return.
#' @return Numeric vector of averages at \code{ages} (0 where no data).
#' @keywords internal
.luy_avg <- function(df, col, years, ages) {
  d <- data.frame(age  = suppressWarnings(as.numeric(as.character(df$age))),
                  year = suppressWarnings(as.numeric(as.character(df$year))),
                  v    = suppressWarnings(as.numeric(as.character(df[[col]]))))
  d <- d[stats::complete.cases(d) & d$year %in% years & d$age %in% ages, ]
  if (nrow(d) == 0L) return(rep(0, length(ages)))
  a <- stats::aggregate(v ~ age, data = d, FUN = mean)
  out <- a$v[match(ages, a$age)]
  out[is.na(out)] <- 0
  out
}

#' Index cohort probabilities of dying
#'
#' No closure rule is applied: ages for which a cohort has no data (after
#' the end of its series, or not yet reached by calendar time) are returned
#' as \code{NA}, so that they never enter the calculation as a probability
#' of dying of 0 or 1.
#' @param cohort_qx Data frame with columns \code{age}, \code{cohort},
#'   \code{qx}.
#' @return A function \code{(age_vector, cohort)} returning the probabilities
#'   of dying (with \code{NA} for unobserved ages), or \code{NULL} if the
#'   cohort has no data at those ages.
#' @keywords internal
.luy_index_qx <- function(cohort_qx) {
  cq <- data.frame(
    age    = suppressWarnings(as.numeric(as.character(cohort_qx$age))),
    cohort = suppressWarnings(as.numeric(as.character(cohort_qx$cohort))),
    qx     = suppressWarnings(as.numeric(as.character(cohort_qx$qx))))
  cq <- cq[stats::complete.cases(cq), ]
  if (nrow(cq) == 0L) stop("'cohort_qx' has no usable rows.", call. = FALSE)
  a_max <- max(cq$age); c_min <- min(cq$cohort); c_max <- max(cq$cohort)
  mat <- matrix(NA_real_, a_max + 1L, c_max - c_min + 1L)
  mat[cbind(cq$age + 1L, cq$cohort - c_min + 1L)] <- cq$qx
  function(age_v, cohort) {
    if (cohort < c_min || cohort > c_max || min(age_v) < 0) return(NULL)
    v <- rep(NA_real_, length(age_v))
    in_tab <- age_v <= a_max
    v[in_tab] <- mat[age_v[in_tab] + 1L, cohort - c_min + 1L]
    if (all(is.na(v))) NULL else pmin(pmax(v, 0), 1)
  }
}

#' Period life table at a fractional year
#'
#' Luy (sheet LT_Berechnung) interpolates l(x) linearly between the tables of
#' calendar years \code{floor(t)} and \code{floor(t)+1}.
#' @return A function of a decimal year returning \eqn{l(x)} indexed by
#'   age + 1 (from the cohort diagonal only ages 30+ are filled), or NULL.
#' @keywords internal
.luy_period_lx_fun <- function(period_lx, qx_get) {
  if (!is.null(period_lx)) {
    pl <- period_lx
    if (!"lx" %in% names(pl)) {
      if (!"qx" %in% names(pl)) {
        stop("'period_lx' needs a column 'lx' or 'qx'.", call. = FALSE)
      }
      pl <- do.call(rbind, lapply(split(pl, pl$year), function(d) {
        d <- d[order(d$age), ]
        d$lx <- cumprod(c(1, 1 - d$qx))[seq_len(nrow(d))]
        d
      }))
    }
    pl <- pl[order(pl$year, pl$age), ]
    tabs <- lapply(split(pl, pl$year), function(d) {
      v <- rep(NA_real_, max(d$age) + 1L); v[d$age + 1L] <- d$lx; v
    })
    get_year <- function(y) tabs[[as.character(y)]]
  } else {
    # only l(30) and l(33+n) are needed: start the diagonal at age 30 so
    # that recent cohorts (young ages) are not required
    get_year <- function(y) {
      v <- c(rep(NA_real_, 30), 1)
      for (a in 30:129) {
        q <- qx_get(a, y - a)
        if (is.null(q) || is.na(q)) break
        v <- c(v, v[length(v)] * (1 - q))
      }
      if (length(v) < 32) NULL else v
    }
  }
  function(t) {
    y0 <- floor(t); fr <- t - y0
    l0 <- get_year(y0); l1 <- get_year(y0 + 1)
    if (is.null(l0)) return(NULL)
    if (is.null(l1) || fr == 0) return(l0)
    m <- min(length(l0), length(l1))
    (1 - fr) * l0[seq_len(m)] + fr * l1[seq_len(m)]
  }
}
